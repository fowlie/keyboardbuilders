/**
 * These pages are tested against a FIXED pair of designs, not against the real seed.
 * The seed is regenerated by `scripts/build_seed.py` whenever a source improves, and
 * a page test that asserts on its contents would fail on a good day's data work
 * while telling nobody anything about the pages. `SeedDesignCatalogTest` covers the
 * real file; this covers the rendering.
 */
// Parts off: the parts seed is checked against the real design and controller
// catalogues at startup, and this class swaps one of them for a fixture.
@SpringBootTest(properties = ["keyboardbuilders.parts.enabled=false"])
@AutoConfigureMockMvc
class DesignsControllerTest {

    @TestConfiguration
    class Fixture {
        @Bean
        @Primary
        fun fixedCatalog(): DesignCatalog = object : DesignCatalog {
            private val designs = listOf(corne, reviung41)
            override fun all() = designs
            override fun bySlug(slug: String) = designs.firstOrNull { it.core.slug.value == slug }
        }

        /**
         * The renames are fixed here for the same reason the catalog is: the real
         * `seed/renames.json` is regenerated by `build_seed.py` and its contents are
         * data work, not behaviour. A test that asserted on `slimorta-main` would go
         * red the day that design is renamed again, which is the one day it should not.
         *
         * `SlugRenames` is `final`, so this CONSTRUCTS it rather than subclassing --
         * the class parses a `Resource` and a `ByteArrayResource` is one. The map
         * points at `reviung41`, a slug the fixed catalog holds, so the redirect can
         * be followed to a 200 rather than merely counted.
         */
        @Bean
        @Primary
        fun fixedRenames(mapper: ObjectMapper) = SlugRenames(
            mapper,
            ByteArrayResource("""{"reviung-41": "reviung41"}""".toByteArray()),
        )

        private val corne = Design(
            core = DesignCore(
                name = DesignName("Corne Cherry v3"),
                slug = Slug("corne-cherry-v3"),
                sources = setOf(SourceRef("https://github.com/foostan/crkbd")),
                firmware = Recorded.Known(setOf(FirmwareRef.Qmk("crkbd/rev1"))),
                layouts = setOf(
                    Layout(KeyCount(42), Recorded.Known(Shorthand(3, 6, 3))),
                    Layout(KeyCount(36), Recorded.Known(Shorthand(3, 5, 3))),
                ),
                switches = setOf(SwitchFootprint.Mx),
                buildMethod = BuildMethod.Pcb(),
                controller = Controller.Socket(ControllerFootprint.ProMicro),
                body = Body.Split(SplitHalves(2), Recorded.Known(true), Recorded.Unknown),
                licensing = Licensing(
                    hardware = LicenseState.Stated(setOf(License.Mit)),
                    firmware = LicenseState.Stated(setOf(License.Gpl2Only)),
                    documentation = LicenseState.Unstated,
                ),
            ),
        )

        private val reviung41 = Design(
            core = DesignCore(
                name = DesignName("Reviung41"),
                slug = Slug("reviung41"),
                sources = setOf(SourceRef("https://github.com/gtips/reviung")),
                firmware = Recorded.Known(setOf(FirmwareRef.Qmk("reviung41"))),
                layouts = setOf(Layout(KeyCount(41))),
                switches = setOf(SwitchFootprint.Mx),
                buildMethod = BuildMethod.Pcb(
                    Recorded.Known(HardestComponent(SolderingDifficulty.ThroughHole, setOf(ComponentKind.Diode)))
                ),
                controller = Controller.Socket(ControllerFootprint.ProMicro),
                body = Body.Unibody,
                licensing = Licensing(
                    hardware = LicenseState.Stated(setOf(License.CcBySa4)),
                    firmware = LicenseState.Stated(setOf(License.Gpl2Only)),
                    documentation = LicenseState.Unstated,
                ),
            ),
            extras = DesignExtras(
                wiring = Recorded.Known(
                    KeyWiring.Matrix(PinCount(4), PinCount(12), DiodeDirection.ColToRow)
                ),
            ),
        )
    }

    @Autowired
    lateinit var mockMvc: MockMvc

    @Test
    fun `the index lists every design with a link to its page`() {
        mockMvc.perform(get("/designs"))
            .andExpect(status().isOk)
            .andExpect(content().string(containsString("Corne Cherry v3")))
            .andExpect(content().string(containsString("Reviung41")))
            .andExpect(content().string(containsString("""href="/designs/corne-cherry-v3"""")))
            .andExpect(content().string(containsString("2 designs")))
    }

    @Test
    fun `an index row carries the shape and the electronics`() {
        mockMvc.perform(get("/designs"))
            .andExpect(content().string(containsString("3x6+3")))
            .andExpect(content().string(containsString("42 / 36 keys")))
            .andExpect(content().string(containsString("<span>split</span>")))
            .andExpect(content().string(containsString("Pro Micro socket")))
    }

    /** The repo owner, the same credit the design page's byline gives. */
    @Test
    fun `an index card says who made the design`() {
        mockMvc.perform(get("/designs"))
            .andExpect(content().string(containsString("""<span class="card-by">by foostan</span>""")))
    }

    /**
     * NO PHOTO, NO EMPTY BOX: the drawing takes the photo's place, so every card in the
     * grid has the same shape. Checked per card, since which fixtures have a real photo
     * in the seed is not this test's business (reviung41 does; corne-cherry-v3 does not).
     */
    @Test
    fun `an index card without a photo draws the board where the photo would be`() {
        val html = mockMvc.perform(get("/designs")).andReturn().response.contentAsString
        val cards = html.substringAfter("<ul class=\"results\">").substringBefore("</ul>")
            .split("<li>").drop(1)
        val photoless = cards.filter { "<img" !in it }

        assertTrue(photoless.isNotEmpty(), "every fixture has a photo, so nothing was checked")
        photoless.forEach { card ->
            assertTrue(
                Regex("""class="card-drawn">\s*<svg class="silhouette"""") in card,
                "a photo-less card draws no board: ${card.take(200)}",
            )
        }
    }

    /** The half count and PCB note are design-page detail (`Body.brief`'s own test). The
     *  silhouette's aria-label still describes the drawing in full, so this looks only
     *  at the visible fact chips. */
    @Test
    fun `an index row does not spell out halves or PCBs`() {
        val html = mockMvc.perform(get("/designs")).andReturn().response.contentAsString
        val chips = Regex("""<span>([^<]*)</span>""").findAll(html).map { it.groupValues[1] }.toList()

        assertTrue(chips.contains("split"), "no split chip at all, so nothing was checked: $chips")
        // "halves" and "reversible", not "PCB": the rail's own option labels may say PCB.
        assertTrue(chips.none { "halves" in it || "reversible" in it }, "a card chip spells out build detail: $chips")
    }

    @Test
    fun `the detail page renders the spec and the licenses`() {
        mockMvc.perform(get("/designs/corne-cherry-v3"))
            .andExpect(status().isOk)
            .andExpect(content().string(containsString("Corne Cherry v3")))
            .andExpect(content().string(containsString("QMK (crkbd/rev1)")))
            .andExpect(content().string(containsString("MIT")))
            .andExpect(content().string(containsString("all rights reserved")))
            .andExpect(content().string(containsString("https://github.com/foostan/crkbd")))
    }

    /**
     * A source link is an off-site link, so it opens in a new tab and wears the glyph
     * that warns it will. Asserted on the rendered anchor rather than on a helper,
     * because `target` and `rel` are the whole behaviour: `noopener` has to survive
     * any later edit that touches the tab, and a new tab with no glyph is the bug.
     */
    @Test
    fun `a source link opens in a new tab and shows an external-link icon`() {
        val body = mockMvc.perform(get("/designs/corne-cherry-v3"))
            .andExpect(status().isOk)
            .andReturn().response.contentAsString
        val link = body.substringAfter("<h2>Sources</h2>").substringBefore("</ul>")
        assertTrue("""href="https://github.com/foostan/crkbd"""" in link, link)
        assertTrue("""target="_blank"""" in link, link)
        assertTrue("""rel="nofollow noopener"""" in link, link)
        assertTrue("""class="ext"""" in link, link)
        assertTrue("""aria-hidden="true"""" in link, link)
    }

    @Test
    fun `the detail page shows an unfilled extra as not recorded rather than omitting it`() {
        mockMvc.perform(get("/designs/corne-cherry-v3"))
            .andExpect(content().string(containsString("Key wiring")))
            .andExpect(content().string(containsString("""<dd class="unrecorded">&mdash; not recorded &mdash;</dd>""")))
    }

    @Test
    fun `a recorded extra is rendered as a value`() {
        mockMvc.perform(get("/designs/reviung41"))
            .andExpect(status().isOk)
            .andExpect(content().string(containsString("4×12 matrix, column-to-row diodes")))
            .andExpect(content().string(containsString("through-hole")))
    }

    /**
     * Forgejo #42: `primaryImageOfPage` names the square thumbnail, not the share card.
     *
     * jte escapes `/` to `\/` inside a `<script>` block -- the standard JSON-in-HTML
     * defence against a value smuggling in a literal `</script>` -- so the assertion
     * matches on the un-escaped URL rather than assume either encoding.
     */
    @Test
    fun `a design with a silhouette states its thumbnail as primaryImageOfPage`() {
        val body = mockMvc.perform(get("/designs/reviung41"))
            .andExpect(content().string(containsString(""""primaryImageOfPage"""")))
            .andReturn().response.contentAsString
        assertTrue("/designs/reviung41/thumbnail.png" in body.replace("\\/", "/"))
    }

    @Test
    fun `a design with no silhouette states no primaryImageOfPage at all`() {
        mockMvc.perform(get("/designs/corne-cherry-v3"))
            .andExpect(content().string(org.hamcrest.Matchers.not(containsString("primaryImageOfPage"))))
    }

    @Test
    fun `an unknown slug is a 404`() {
        mockMvc.perform(get("/designs/no-such-board")).andExpect(status().isNotFound)
    }

    /**
     * Forgejo #38. Ticket 07 decision 8: *"slugs are mutable and old ones keep
     * resolving. A machine-guessed name is a first draft too, so a rename leaves a
     * redirect rather than a dead link."* Two places in the repo claimed this was
     * already true; no code did it, and `/designs/3-w6` was dead for four days.
     *
     * **301 and not 308**, deliberately: both are permanent, and 301 is what a crawler
     * expects for a moved page. The historical difference -- 301 lets a client turn a
     * POST into a GET -- cannot arise here, because this route is GET-only.
     */
    @Test
    fun `a former slug redirects permanently to the design's current page`() {
        mockMvc.perform(get("/designs/reviung-41"))
            .andExpect(status().isMovedPermanently)
            .andExpect(header().string("Location", "/designs/reviung41"))
    }

    /**
     * The half a redirect table gets wrong. A 301 pointing at a slug that publishes
     * nothing is worse than the 404 it replaced, because it hides WHICH url was wrong
     * -- so the destination is followed here rather than assumed. `build_seed.py`
     * refuses to emit such a row; this is the same guard at the other end.
     */
    @Test
    fun `the page a former slug redirects to actually resolves`() {
        val location = mockMvc.perform(get("/designs/reviung-41"))
            .andReturn().response.getHeader("Location")!!
        mockMvc.perform(get(location)).andExpect(status().isOk)
    }

    /**
     * A removal is not a rename. `seed/renames.toml` records both -- `now = false` for
     * the pages that were simply wrong, and those are emitted to no map at all -- so a
     * slug nothing renamed must still be a 404 and not a redirect to a guess.
     */
    @Test
    fun `a slug that was removed rather than renamed stays a 404`() {
        mockMvc.perform(get("/designs/8keyv4")).andExpect(status().isNotFound)
    }

    /**
     * The SHARE CARD answers the same slug question, so it has to answer it the same
     * way. Two endpoints keyed by one slug that disagree about whether it exists is a
     * inconsistency nobody would predict from either one's code.
     *
     * And "resolve the design but serve it under the old url" is the trap here rather
     * than the shortcut: `OgImageController` passes the REQUESTED slug to
     * `silhouettes.keysFor`, so a card served under a former slug would draw with no
     * silhouette at all -- a silently degraded image, which is worse than either a
     * redirect or a 404 because nothing reports it.
     */
    @Test
    fun `a former slug's share card redirects to the current one`() {
        mockMvc.perform(get("/designs/reviung-41/og.png"))
            .andExpect(status().isMovedPermanently)
            .andExpect(header().string("Location", "/designs/reviung41/og.png"))
    }

    @Test
    fun `a share card for a slug nothing renamed is still a 404`() {
        mockMvc.perform(get("/designs/8keyv4/og.png")).andExpect(status().isNotFound)
    }

    /** The same slug-resolution contract as the share card, and the same fixture proves it. */
    @Test
    fun `a former slug's search thumbnail redirects to the current one`() {
        mockMvc.perform(get("/designs/reviung-41/thumbnail.png"))
            .andExpect(status().isMovedPermanently)
            .andExpect(header().string("Location", "/designs/reviung41/thumbnail.png"))
    }

    @Test
    fun `a search thumbnail for a slug nothing renamed is still a 404`() {
        mockMvc.perform(get("/designs/8keyv4/thumbnail.png")).andExpect(status().isNotFound)
    }

    /**
     * NO GENERIC IMAGE. `corne-cherry-v3` is a real design with no entry in
     * `silhouettes.json` (the fixture's slug does not match the seed's), so a thumbnail
     * would have nothing to draw but a blank square -- the one thing Google's guidance
     * names as worse than no image at all.
     */
    @Test
    fun `a design with no silhouette gets no thumbnail rather than a blank one`() {
        mockMvc.perform(get("/designs/corne-cherry-v3/thumbnail.png")).andExpect(status().isNotFound)
    }

    @Test
    fun `a design with a silhouette gets a real thumbnail`() {
        mockMvc.perform(get("/designs/reviung41/thumbnail.png"))
            .andExpect(status().isOk)
            .andExpect(content().contentType("image/png"))
    }

    /** A slug value class would throw on this; a stranger's URL must not be a 500. */
    @Test
    fun `a slug-shaped-nothing is a 404, not a server error`() {
        mockMvc.perform(get("/designs/Not_A_Slug")).andExpect(status().isNotFound)
    }
}
